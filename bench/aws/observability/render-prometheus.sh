#!/usr/bin/env bash
# Render a Prometheus scrape config from a STATE.json: every ably-server node,
# NATS server, load generator, publisher and host, plus postgres_exporter.
#
#   observability/render-prometheus.sh STATE.json > prometheus.yml
#
# Ports can be overridden with SERVER_DEBUG_PORT, NODE_EXPORTER_PORT,
# NATS_EXPORTER_PORT and LOADGEN_METRICS_PORT.
set -euo pipefail
state=${1:?usage: render-prometheus.sh STATE.json}
[ -s "$state" ] || { echo "no such state file: $state" >&2; exit 1; }
: "${SERVER_DEBUG_PORT:=6060}" "${NODE_EXPORTER_PORT:=9100}" "${NATS_EXPORTER_PORT:=7777}" "${LOADGEN_METRICS_PORT:=9101}"

# job <name> <port> <role>...: one scrape job over the instances with those roles.
job() {
  local name=$1 port=$2 lines
  shift 2
  local roles
  roles=$(printf '"%s",' "$@")
  lines=$(jq -r --argjson port "$port" "
    (.instances // {}) | to_entries | map(select(.value.role as \$r | [${roles%,}] | index(\$r)))
    | sort_by(.key)[] | select(.value.private_ip != null and .value.private_ip != \"\")
    | \"      - targets: ['\" + .value.private_ip + \":\" + (\$port|tostring) + \"']\n        labels: {name: '\" + .key + \"', role: '\" + .value.role + \"'}\"" "$state")
  [ -n "$lines" ] || return 0
  printf '  - job_name: %s\n    static_configs:\n%s\n' "$name" "$lines"
}

project=${PROJECT_TAG:-ably-server-scale}
cat <<YAML
# Generated by render-prometheus.sh from STATE.json. Do not edit by hand.
global:
  scrape_interval: 5s
  evaluation_interval: 15s
  external_labels: {project: '$project'}
scrape_configs:
  - job_name: prometheus
    static_configs:
      - targets: ['localhost:9090']
YAML
job ably-server "$SERVER_DEBUG_PORT" node
job node "$NODE_EXPORTER_PORT" node nats loadgen publisher conductor pgdriver
job nats "$NATS_EXPORTER_PORT" nats
job loadgen "$LOADGEN_METRICS_PORT" loadgen publisher
if [ "$(jq -r '(.postgres.instances // {}) | length' "$state")" -gt 0 ]; then
  cat <<'YAML'
  - job_name: postgres
    static_configs:
      - targets: ['postgres-exporter:9187']
        labels: {role: postgres}
YAML
fi
